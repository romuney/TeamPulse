-- 1. Где таблица: база, движок, сколько строк
SELECT database, name, engine, total_rows
FROM system.tables
WHERE name ILIKE '%monitoring_work_activity%'
ORDER BY database, name;

-- 2. Колонки таблицы: имя, тип, комментарий
SELECT database, table, name, type, comment
FROM system.columns
WHERE table ILIKE '%monitoring_work_activity%'
ORDER BY database, table, position;
