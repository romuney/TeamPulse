-- ============================================================================
-- 0а. SQL Lab — структура таблицы ClickHouse
--
-- Зачем: по ответам я пойму таблицу — колонки и типы, что одна строка, какие
-- колонки справочные, где пусто — и сопоставлю её с метриками отчёта
-- (SOURCES.md, §5, §7 и §17).
--
-- SQL Lab в Proteus пропускает только SELECT и DESCRIBE, а служебные таблицы
-- ClickHouse в нём закрыты. Поэтому структура здесь — через DESCRIBE,
-- остальное — обычными SELECT по самой таблице.
--
-- Как: выделите один запрос — от DESCRIBE или SELECT до точки с запятой — и
-- выполните (Ctrl+Enter). Ответ — «Скопировать в буфер» или CSV — пришлите
-- в чат с номером запроса. Другая таблица — замените её имя во всём файле.
--
-- Персональных данных здесь нет: запросы 1–4 показывают только имена колонок,
-- типы и счётчики. Запросы 5–9 — после ответа на 1: в них нужны имена ваших
-- колонок, и пока они не вписаны, запросы нарочно не выполнятся.
--
-- Проверено на ClickHouse 24.8.
-- ============================================================================


-- 1. Колонки: имя, тип, значение по умолчанию, комментарий.
DESCRIBE TABLE prod_proteus.hr_structure_overall;


-- 2. Сколько строк.
SELECT count() AS rows FROM prod_proteus.hr_structure_overall;


-- 3. Сколько разных значений в каждой колонке — одна строка, колонка на
--    колонку. Видно, что одна строка таблицы (сотрудник за день? за месяц?),
--    какие колонки — справочники (мало значений), а какие — константы.
--    Это счётчики, самих значений здесь нет. Думает дольше минуты —
--    запустите 3б: то же по первому миллиону строк.
SELECT count() AS rows, * APPLY(uniq) FROM prod_proteus.hr_structure_overall;

-- 3б.
SELECT count() AS rows, * APPLY(uniq) FROM (SELECT * FROM prod_proteus.hr_structure_overall LIMIT 1000000);


-- 4. Заполненность: сколько непустых значений в каждой колонке
--    (NULL не считается, пустая строка считается).
SELECT count() AS rows, * APPLY(count) FROM prod_proteus.hr_structure_overall;


-- ---------------------------------------------------------------------------
-- 5–9 — после ответа на 1. Вместо <…> впишите имена своих колонок: до этого
-- запросы нарочно не выполнятся. Могу прислать их уже заполненными.
-- ---------------------------------------------------------------------------

-- 5. Диапазоны: минимум и максимум по каждой колонке — даты, коды, числа.
--    В EXCEPT — колонки с ФИО, почтой, логином, табельным номером, зарплатой:
--    минимум колонки с ФИО — это чьё-то имя. EXCEPT молча пропускает имя,
--    которого в таблице нет, — сверьте имена с ответом на 1.
SELECT 'min' AS what, * EXCEPT (<колонки с ФИО, почтой, логином, табельным, зарплатой>) APPLY(min)
FROM prod_proteus.hr_structure_overall
UNION ALL
SELECT 'max', * EXCEPT (<те же колонки>) APPLY(max)
FROM prod_proteus.hr_structure_overall;


-- 6. Двадцать строк для примера — без персональных данных. Ключ сотрудника
--    показан хешем: видно, что строки одного человека повторяются, а кто он —
--    нет. Сам ключ — в EXCEPT вместе с остальными колонками.
SELECT cityHash64(<ключ сотрудника>) % 100000 AS person_hash,
       * EXCEPT (<ключ сотрудника>, <колонки с ФИО, почтой, логином, табельным, зарплатой>)
FROM prod_proteus.hr_structure_overall
LIMIT 20;


-- 7. Строки по месяцам: за какой период данные и нет ли провалов.
SELECT toStartOfMonth(<колонка даты>) AS month, count() AS rows
FROM prod_proteus.hr_structure_overall
GROUP BY month
ORDER BY month;


-- 8. Значения справочной колонки (покраска, грейд, тип оформления…) — той,
--    где в ответе на 3 мало разных значений (до ~50).
SELECT <колонка> AS value, count() AS rows
FROM prod_proteus.hr_structure_overall
GROUP BY value
ORDER BY rows DESC
LIMIT 50;


-- 9. Зерно: одна ли строка на сотрудника и дату. keys = rows — да; keys меньше —
--    у человека на дату несколько строк (переводы, совместительство), и это
--    важно для численности.
SELECT count() AS rows, uniqExact(<ключ сотрудника>, <колонка даты>) AS keys
FROM prod_proteus.hr_structure_overall;
