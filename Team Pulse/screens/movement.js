/* ============================================================================
   screens/movement.js — Движение персонала. По два графика на каждой вкладке:

   «Баланс за период»  — динамика численности сверху, водопад её изменения снизу.
                         Численность и потоки, которые её двигают, читаются вместе:
                         линия показывает, ЧТО получилось, водопад — из чего.
   «Найм, отток и переводы» — внешние потоки сверху (найм / отток), внутренние
                         снизу (переводы в команду / из команды). Обе пары —
                         дивергентные бары: один бар, разрезанный осью, а не два
                         рядом, и одна шкала на оба плеча.

   «Замещение и темпы» — растёт ли команда (итерация 28, бизнес-анализ):
                         коэффициент замещения сверху, найм и отток на 100
                         человек снизу. Темпы, в отличие от людей, сравнимы
                         с базой и между командами разного размера.

   Два fill-графика в панели делят её высоту пополам без правок CSS.
   ========================================================================== */
(function(){
'use strict';
const D=window.TPDATA, G=window.TPDRAW, U=window.TPUI, SC=window.TPSCREENS;

/* 20.10: начало — численность на 1-е число первого месяца окна (а не на конец этого месяца:
   его найм и отток уже в потоках, и месяц уходил в «Прочее»), конец — на дату данных; даты —
   под подписями «Начало» и «Конец» */
/* поставка 105: водопад — из замкнутой витрины движения (flow_*): начало, найм, отток, переводы в и из, конец одной
   логикой, «прочего» нет по построению. Переводы здесь — любое изменение принадлежности (другое подразделение, тип
   численности, возвращение), поэтому они не равны карточкам «Переводы» (те — по флагам источника, сверены с мастером) */
function balancedSteps(lp){
  /* 09.11 (владелец: одна методология на метрику; переводы — только флаги источника, их сумма): начало, конец и отток —
     из витрины движения (flow_*; отток = «Ушли, чел», hub checks № 32), найм — событие дня найма, то же, что «Найм, чел»
     (flow_hire = hire датасета), переводы — те же, что карточки «Переводы» (флаги in / out). Флаги покрывают всё
     движение: остаток — только сбой данных (изменение без флага), шаг «Без флага в источнике» виден лишь тогда */
  const F=D.FLOW;
  const hc=D.aggregate(lp,F?'flow_fin':'hc_total'), begin=hc[0], end=hc[D.LAST];
  const hire=D.winSum(lp,F?'flow_hire':'hire'), tin=D.winSum(lp,'transfer_in');
  const attr=-D.winSum(lp,F?'flow_fire':'attrition'), tout=-D.winSum(lp,'transfer_out');
  const other=end-(begin+hire+tin+attr+tout);
  return [{name:'Начало',sub:'на конец '+D.WIN_FROM,value:begin,total:true},{name:'Найм',value:hire},
    {name:'Переводы в',value:tin},{name:'Отток',value:attr},{name:'Переводы из',value:tout}].concat(
    Math.abs(other)<0.5?[]:[{name:'Без флага в источнике',value:other,note:D.REAL?'Изменение численности, у которого в '+
      'источнике нет флага найма, увольнения или перевода, — сбой данных. Найм, отток и переводы (флаги in / out) покрывают '+
      'всё движение людей.':'В демо численность и потоки генерируются независимо.'}],
    /* поставка 137, п. 2 (владелец): у «Конца» — точная дата данных, а не месяц */
    [{name:'Конец',sub:'на '+D.ASOF_LABEL,value:end,total:true}]);
}

/* 26.10-б, правки п. 1: «Движение по специализациям» — после переводов: с начала года по специализации.
   27.10-в, п. 5: «Остальные» раскрываются вторым уровнем, как регион в «Структуре»; «сальдо» → «итого».
   28.10, п. 1: четыре составляющих — найм, переводы в, отток, переводы из; итого = найм + в − отток − из; полоса:
   влево — отток и переводы из, вправо — найм и переводы в (общая шкала). ИТОГО первой строкой = карточкам с начала
   года. Пробник без переводов по специализации (ноутбук до 28.10) — без двух колонок переводов */
function specMove(lp,ctx){
  const rs=D.specMovement(lp);
  if(!rs.length)return '';
  /* 31.10, файл итерации п. 4: сортировка по любой числовой колонке — клик по шапке (по умолчанию — найм), по убыванию;
     «Остальные» — после сортировки, раскрываются как раньше */
  const sk=ctx&&ctx.S&&ctx.S.spmSort||'hire';
  rs.sort((a,b)=>(b[sk]||0)-(a[sk]||0)||a.name.localeCompare(b.name,'ru'));
  const trf=!D.REAL||D.SPM_TRF, K='rest:spm', open=!!(ctx&&ctx.mixOpen.has(K)), top=rs.slice(0,12), rest=rs.slice(12);
  const S=(a,k)=>a.some(z=>z[k]==null)?null:a.reduce((t,z)=>t+z[k],0), agg=(a,o)=>Object.assign(o,{hc0:S(a,'hc0'),
    hire:S(a,'hire'),tin:S(a,'tin'),exit:S(a,'exit'),tout:S(a,'tout'),chg:S(a,'chg'),hc1:S(a,'hc1'),net:S(a,'net')});
  if(rest.length)top.push(agg(rest,{name:'Остальные',note:rest.length+' '+U.plural(rest.length,['специализация','специализации','специализаций']),
    exp:1}));
  /* 10.11 (владелец: «строку итого на специализациях убери — сбивает: общий тотал есть наверху, а здесь мы считаем события,
     и их больше, чем переводов команды»): строки «Итого» в таблице нет — переводы строки включают смену специализации
     внутри команды, их сумма больше «Переводов в / из» команды в водопаде и карточках */
  if(open)rest.forEach(z=>top.push(Object.assign({sub:1},z)));
  const tree=rest.length>0, esc=U.esc;
  const lbl=z=>!tree?'':z.exp?'<button class="caret-btn"'+(open?' data-open="1"':'')+' data-btexp="'+K+'" aria-label="'+
    (open?'Свернуть':'Раскрыть')+'">'+(open?'▾':'▸')+'</button>':'<span class="caret-spacer"></span>';
  /* 29.10, п. 1: найм, переводы в, отток, переводы из (без «Итого» и полосы). 31.10, п. 7: по краям — численность на
     начало периода (до движений) и на конец (после них) */
  /* поставка 121 (критики 119: «переводы в 45» в таблице при 14 в карточке «Переводы в команду»): в витрине движения (SPM_FSM)
     колонки — переходы, в них и смена специализации внутри команды; названы «Переходы», чтобы не путать с карточками */
  const tw='Переводы';
  const cols=[['hc0','На начало']].concat([['hire','Найм']]).concat(trf?[['tin',tw+' в']]:[]).concat([['exit','Отток']])
    .concat(trf?[['tout',tw+' из']]:[]).concat(D.SPM_CHG?[['chg','Внутри юнита']]:[]).concat([['hc1',D.SPM_END?'На конец':'Сейчас']]);
  /* поставка 137, п. 6 (владелец): детализации по клику у строки специализации нет — строка не кликается (без подсказки
     о клике и подсветки); кликаются только шапка (сортировка) и «Остальные» (раскрыть) */
  const row=z=>'<tr'+(z.total?' class="total top"':z.exp?' class="urow" data-btexp="'+K+'"'+U.tipAttr({title:'Остальные',
        text:open?'Клик — свернуть.':'Кликни, чтобы посмотреть остальные.'}):z.sub?' class="lvl2"':'')+'><td class="txt">'+
      (tree?'<span class="row-label">'+(z.total?'<span class="caret-spacer"></span>':lbl(z))+'<span class="row-body">':'')+esc(z.name)+
      (z.note?'<span class="unit-sub">'+esc(z.note)+'</span>':'')+(tree?'</span></span>':'')+'</td>'+
      cols.map(c=>'<td class="num'+(c[0]==='hc0'||c[0]==='hc1'?' spm-hc':'')+'">'+(z[c[0]]==null?'—':D.fmtNumber(z[c[0]],c[0]==='chg'))+'</td>').join('')+'</tr>';
  return '<div class="bt-group spm"><div class="bt-cap">Движение по специализациям<span class="bt-sub">'+U.esc(D.CNT_TEXT)+', чел</span></div>'+
    '<div class="mx-wrap"><table class="ptable btable compact spm4"><colgroup><col>'+cols.map(()=>'<col>').join('')+
    '</colgroup><thead><tr><th class="txt"></th>'+cols.map(c=>'<th class="num tsort'+(c[0]===sk?' on':'')+(c[0]==='hc0'||c[0]==='hc1'?' spm-hc':'')+'" data-spmsort="'+c[0]+'"'+
      U.tipAttr({title:c[1],text:c[0]===sk?'Сейчас — по убыванию.':'Клик — сортировать по убыванию.'})+'>'+c[1]+'</th>').join('')+'</tr></thead><tbody>'+
    top.map(row).join('')+'</tbody></table></div>'+
    '<div class="tbl-note">'+U.esc(D.CNT_TEXT.replace(/^./,x=>x.toUpperCase()))+'. На начало — численность на конец декабря, '+
      (D.SPM_END?'на конец — '+(D.PER_PART?'на '+U.esc(D.ASOF_LABEL):U.esc(D.MONTH_GEN[D.PER_C]))+', после наймов, увольнений и переводов':'«сейчас» — на дату данных')+'. '+
      (D.SPM_FSM?'В каждой строке: на начало + найм + переводы в − отток − переводы из = на конец. Переводы строки — это и '+
        'перевод в команду или из неё, и смена специализации внутри команды, поэтому их сумма по строкам больше, чем '+
        'переводов команды в водопаде выше. Найм — в специализации на день найма.':D.SPM_CHG?'Переводы — только смена юнита на уровне выбранного подразделения: перемещение между его подразделениями переводом не считается. '+
        'Внутри юнита — смена специализации или среза без перевода (+ пришли в специализацию, − ушли): строки сходятся.'
        :'Итого — как в карточках движения. Переводы — перевод в выбор или из него по флагам фильтров и смена специализации внутри выбора: строки сходятся.')+
      (trf?'':' Переводы по специализациям появятся, когда ноутбук отчёта обновят.')+'</div></div>';
}


SC.blocks.movement={
  /* Итерация 32 (фидбэк 12.10): «вначале waterfall, а потом только динамики»,
     и вся динамика — численность, найм и отток, переводы — на одном листе,
     «чтобы было видно, что на что повлияло». Глава «Замещение и темпы»
     снята: коэффициент замещения и найм на 100 человек на отдельном листе
     читались как непонятные метрики. Сами метрики остались в карточках
     и в таблице подразделений — их можно скрыть в «Настрой свой дашборд». */
  subTabs:[['balance','Обзор за год'],['dynamics','Динамика по месяцам']],
  defaultSub:'balance',
  title(sub){return sub==='dynamics'
    ? 'Численность, найм, отток и переводы по месяцам'
    : 'Из чего сложилось изменение численности'},
  view(ctx){
    if(ctx.sub==='dynamics'){
      return SC.metricLine('hc_total',ctx.lp,ctx.bl,ctx.S,{h:240,title:'Численность, чел',ann:ctx.ann.hc_total})+
        SC.yoyPair(ctx.lp,'hire','attrition',
        {h:240,title:'Найм и отток, чел',
         legend:[{name:'Приняли',color:G.C_IN},{name:'Уволились',color:G.C_OUT}]})+
        /* та же гамма, что у найма и оттока: человек пришёл — C_IN, ушёл — C_OUT.
           Отдельный «приглушённый» цвет для внутренних переводов заводить нельзя,
           иначе водопад рядом красит те же переводы зелёным и красным. */
        SC.yoyPair(ctx.lp,'transfer_in','transfer_out',
        {h:240,title:'Переводы внутри компании, чел',
         legend:[{name:'В команду',color:G.C_IN},{name:'Из команды',color:G.C_OUT}]})+specMove(ctx.lp,ctx);
    }
    /* обзор: водопад года и то, что из него нужно вынести (story.js — insights) */
    return G.chart('waterfall',{steps:balancedSteps(ctx.lp)},{main:true,
        title:'Изменение численности с '+D.WIN_START+', чел',
        legend:[{name:'Начало и конец',color:G.C_TOTAL},{name:'Пришли',color:G.soft(G.C_IN)},{name:'Ушли',color:G.soft(G.C_OUT)}]})+
      U.storyFacts(ctx.story&&ctx.story.insights,'Что важно');
  }
};
})();
