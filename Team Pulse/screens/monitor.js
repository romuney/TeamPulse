/* ============================================================================
   screens/monitor.js — Мониторинг работы.

   «Динамика» — недоработчики и доля улучшивших оценку в ревью панелями.
   «Лоу-перформеры» сняты 15.10: такого понятия в компании нет; мониторинг по
   каталогу HQ — недоработка, переработка, звонки, прогулы, выходные (план). Все шкалы от нуля: раньше ось резалась под диапазон значений, и
   колебание 6,1→6,9% выглядело обвалом. Ревью — ступенька: цикл раз в полгода.
   «Ревью» (итерация 28, дашборд 34661) — итоги последнего цикла: динамика
   оценок к прошлому циклу и оценки по грейду, стажу и роли.

   21.10 — «Рабочая активность» по файлу Антона «Мониторинг работы»: KPI-полоса из пяти
   показателей за последнюю закрытую неделю (недоработка, переработка, звонки в Толк,
   прогулы, работа в выходные), состав по категориям столбиками (месяцы / недели), линии
   часов в день и доли звонков, в таблице подразделений — колонки мониторинга и
   мини-график недо- и переработки за 12 недель. Клик по строке таблицы пересчитывает KPI
   и графики, клик по столбику отмечает период на линиях, Escape снимает выбор.

   Поставка 71 (мониторинг по дням Адели): на настоящих данных — по месяцам звонки в Толк, прогулы и работа в
   выходные (KPI с изменением к прошлому месяцу), линии часов в день и доли звонков. Недели — с витриной по неделям.
   ========================================================================== */
(function(){
'use strict';
const D=window.TPDATA, G=window.TPDRAW, U=window.TPUI, SC=window.TPSCREENS;

const C=G.C_MON;
/* доля — тем же округлением, что метрика «Недоработчики» (ratioAt → fmtVal): иначе 8,4% и 8,5% за один месяц */
/* последняя закрытая неделя и предыдущая; в пробнике без витрины по неделям — месяцы */
/* поставка 104: таблица подразделений — последний закрытый месяц (cl; незакрытый теперь тоже в ряду), как подпись колонок */
function wk(md){const W=md.months, i=Math.max(0,W.findIndex(p=>p.cl));return {cur:W[i],prev:W[i-1]||W[i]}}
/* блок графика, данных для которого в пробнике нет: заголовок на месте, плашка «в разработке» */
function monPh(title,what){
  return '<div class="mon-ph"><div class="bt-cap">'+U.esc(title)+'</div>'+
    U.devNote({stage:5,t:what+' Нужна витрина мониторинга по неделям: где она лежит — запрос 0л.'})+
    '<div class="tbl-note">'+U.esc(what)+' Появится с витриной мониторинга.</div></div>';
}

/* поставка 104 (заказчик): под заголовком — «В среднем за неделю / месяц» по закрытым периодам графика, как итог за
   период у графиков динамики; год к году здесь нет (16 недель / 6 месяцев). Часы и звонки — взвешенно, как точки */
function perLine(P,wk){
  const C=P.filter(p=>!p.pt);
  if(!C.length)return null;
  const head='В среднем за '+(wk?'неделю':'месяц')+', '+C[0].label+(C.length>1?'–'+C[C.length-1].label:'');
  const avg=k=>C.reduce((a,p)=>a+(p[k]||0),0)/C.length, n=v=>D.fmtInt?D.fmtInt(Math.round(v)):String(Math.round(v));
  const f1=v=>(Math.round(v*10)/10).toFixed(1).replace('.',',');
  const sum=k=>C.reduce((a,p)=>a+(p[k]||0),0), wt=C.every(p=>p.pdw!=null);
  return {
    cats:()=>{const hc=avg('hc');return {head:head,parts:[['under','недоработка'],['over','переработка']].map(c=>({name:c[1],
      cur:n(avg(c[0]))+' чел'+(hc?' ('+Math.round(avg(c[0])/hc*100)+'%)':'')}))}},
    hours:()=>{const v=wt&&sum('pdw')?sum('hrw')/sum('pdw'):avg('hours');return v?{head:head,cur:f1(v)+' ч/день'}:null},
    talk:()=>{const v=wt&&sum('hrw')?sum('tkw')/sum('hrw')*100:avg('talk');return v?{head:head,cur:f1(v)+'%'}:null},
    ppl:ks=>({head:head,cur:n(ks.reduce((a,k)=>a+avg(k),0))+' чел'})};
}
/* 30.10, заказчик: плашки KPI сняты — прогулы, работа в выходные и звонки в Толк теперь графиками по периодам
   (столбик — люди, части — сколько дней или какая доля звонков); нет таких данных в периоде — графика нет */
/* поставка 104: по неделям прогулов и работы в выходные нет (у мастер-дашборда тоже) — только звонки по доле недели */
function extraCharts(P,pl){
  const z=P.length?P[P.length-1]:{};
  if(z.ab25==null&&z.t23==null)return '';
  const st=(t,cats)=>G.chart('stack',{periods:P,cats:cats,unit:' чел'},
    {title:t,legend:cats.map(c=>({name:c[1],color:c[2]})),sm:true,period:pl&&pl.ppl(cats.map(c=>c[0]))});
  return (z.ab25!=null?st('Прогулы, чел',[['ab25','2–5 дней',C.per],['ab5','больше 5 дней',C.per2]])+
    st('Работа в выходные, чел',[['we25','2–5 дней',C.per],['we5','больше 5 дней',C.per2]]):'')+
    st('Звонки в Толк от 20% рабочего времени, чел',[['t23','20–30%',C.talk0],['t35','30–50%',C.talk],['t5','больше 50%',C.talk2]]);
}

SC.blocks.monitor={
  /* 27.10-в, п. 4: ревью скрыто до следующего релиза (D.OFF_SUBS) */
  /* 06.11: шаг «По неделям» (поставка 104) снят вместе с недельной витриной — источник недель ещё не готов */
  subTabs:[['activity','Рабочая активность'],['review','Ревью']].filter(t=>!D.OFF_SUBS.has('monitor.'+t[0])),
  defaultSub:'activity',
  /* 30.10: KPI-полоса блока снята по просьбе заказчика (плашки KPI — ни на одной вкладке) */
  /* колонки таблицы подразделений: последний закрытый период, сортировка по клику на шапку */
  cols:[
    /* 26.10, ревью критиков: знаменатель — люди с категорией мониторинга, а не «активная численность HQ» (343 > 337) */
    /* 30.10, критики: «343 в мониторинге против 337 в шапке» — это не численность, а все, у кого была категория за период
       (в т.ч. ушедшие в его середине) */
    /* поставка 103 (файл 9, п. 1): в мониторинге — численность на конец периода (как в шапке): у каждого одна категория,
       без записи мониторинга — «не размечено»; ушедшие в течение периода не считаются */
    {k:'hc',name:'В мониторинге, чел.',tip:'Численность на конец последнего закрытого периода — та же, что в шапке: у каждого одна категория мониторинга (норма, недоработка, переработка, не размечено). Ушедшие в течение периода не считаются; без записи мониторинга — «не размечено».',val:md=>wk(md).cur.hc},
    /* поставка 90: таблица — люди за последний закрытый месяц, окно подписано под названием */
    {k:'under',name:'Недоработчики',per:'за '+D.PER_MON,tip:'Активность ниже нормы в последнем закрытом периоде, человек.',val:md=>wk(md).cur.under,share:true},
    {k:'over',name:'Переработчики',per:'за '+D.PER_MON,tip:'Активность выше нормы в последнем закрытом периоде, человек.',val:md=>wk(md).cur.over,share:true},
    /* 28.10, п. 2: в таблице подразделений — только численность, недоработка и переработка (Толк и динамика сняты) */
  ],
  title(sub){return sub==='review'?'Итоги ревью: последний цикл, '+D.CMP.cur
    :'Мониторинг рабочей активности'},
  view(ctx){
    if(ctx.sub==='review'){
      const rv=D.reviewProfile(ctx.lp);
      /* Три группы в одной тепловой таблице, а не три таблицы: вопрос один —
         «у кого оценки выше», и группы читаются в одних колонках. ИТОГО — общее
         распределение оценок; края каждой группы с ним сходятся. */
      return U.btStack([
        U.btGroup({cap:'По сравнению с прошлым ревью',capSub:'кого оценили',head:'',
          valueHead:'Человек',metricKey:'hc_total',compact:true,
          items:rv.dyn.map(x=>({name:x.name,note:x.note,value:x.value,color:G.C_REVIEW}))}),
        '<div class="bt-group"><div class="bt-cap">Оценки по группам<span class="bt-sub">доля людей в строке</span></div>'+
        U.heatTable({cols:rv.scores.map(x=>({name:x.name,tip:x.full})),
          total:{name:'ИТОГО',cells:rv.scores.map(x=>x.value)},
          groups:rv.groups.map(g=>({name:g.name,rows:g.rows.map((n,i)=>({name:n,cells:g.cells[i]}))}))})+
        '</div>'])+'<div class="tbl-note">Доли в строке складываются в 100%. Сколько это человек — в подсказке.</div>';
    }
    const md=D.monData(ctx.lp);
    if(!md)return U.empty('Нет данных мониторинга','Витрина мониторинга по неделям ещё не подключена к отчёту.');
    /* 05.11, заказчик: отметка периода кликом по столбику снята — графики без выделения */
    const wk=false, P=md.months;
    /* пробник без витрины по неделям и без мониторинга по дням: часы и звонки — заглушки */
    if(md.monthly&&!md.daily)return '<div class="sm-grid">'+G.chart('stack',{periods:P},{title:'Состав по категориям, чел',
        legend:G.MON_CATS.map(c=>({name:c[1],color:C[c[0]]})),h:270})+
      /* 22.10: блоки динамики рабочей активности и звонков в Толк стоят на месте (файл Антона, 2.3 и 2.4);
         в основной таблице часов и звонков нет — они заполнятся с витриной мониторинга */
      monPh('Средняя рабочая активность, ч/день','Средняя рабочая активность в часах в день по месяцам и неделям.')+
      monPh('Средняя доля звонков в Толк, % рабочего времени','Доля разговоров в Толк от рабочего времени, среднее по месяцам и неделям.')+'</div>';
    /* 31.10 (поставка 82): графики мониторинга — малые кратные с одной осью периодов: на широкой панели сеткой.
       Поставка 104 (заказчик): низкие (sm) — лист короче; под заголовком — среднее за период */
    const pl=perLine(P,wk);
    return '<div class="sm-grid">'+G.chart('stack',{periods:P},{title:'Состав по категориям, чел',
        legend:G.MON_CATS.map(c=>({name:c[1],color:C[c[0]]})),period:pl&&pl.cats()})+
      G.chart('pline',{periods:P,key:'hours'},{title:'Средняя рабочая активность, ч/день',name:'Средняя рабочая активность',sm:true,period:pl&&pl.hours()})+
      G.chart('pline',{periods:P,key:'talk'},{title:'Средняя доля звонков в Толк, % рабочего времени',name:'Средняя доля звонков в Толк',fmt:'pct',sm:true,period:pl&&pl.talk()})+
      extraCharts(P,pl)+'</div>';
  }
};
})();
