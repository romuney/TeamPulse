/* ============================================================================
   screens/office.js — Посещаемость офисов. Пять под-вкладок:

   «Календарь»      — подневная сетка за последние два месяца периода плюс
                      разбивка по дням недели. Отвечает на вопрос «когда людей
                      в офисе больше», на который месячная линия ответить не может.
   «Кто и где ходит» (22.10: «Города», «Кто ходит» и «Динамика» — одна вкладка, без грейдов):
                      сверху динамика посещаемости, ниже сегмент (руководители /
                      сотрудники), ниже локация (города). Строки кликаются: выбор
                      сегмента и города складывается и пересчитывает динамику и
                      другую таблицу; выбор — на полке срезов, Escape снимает.
   «Бронирование»   — нарушения бронирования: бронь без прихода и приход
                      без брони, динамикой и разбором последнего месяца.

   Дни недели — таблицей, а не барами: день недели это атрибут, а для разбивок
   по атрибутам в проекте таблица с полосой в ячейке (то же правило, что у грейдов
   и причин увольнений). Доля отключена: доля одного процента в сумме процентов
   ничего не значит.

   Поставка 66 (посещения Адели): в пробнике всё это — на настоящих данных, если они есть в ответе
   (D.OFF_LIVE): календарь по дням двух месяцев, сегмент — руководители и сотрудники (клик — их
   динамика), города офиса — посещения последнего месяца (без выбора: город есть у посещения, а не у
   сотрудника), бронирования. Чего нет — генератор макета.
   ========================================================================== */
(function(){
'use strict';
const D=window.TPDATA, G=window.TPDRAW, U=window.TPUI, SC=window.TPSCREENS;
const esc=U.esc;

/* 15.10: сноска «в макете сгенерировано» снята — что цифры условные, говорит
   плашка «в разработке» над вкладкой; сноска объясняет только, как читать */
const CAL_NOTE='Посещаемость дня — доля сотрудников с рабочим днём, которые пришли в офис.';

/* выбор сегмента и города — подпись для графика и полки */
const offLabel=x=>[x.seg?x.seg.name:'',x.city?x.city.name:''].filter(Boolean).join(' · ');

/* поставка 136, п. 15 (владелец: «в посещаемости нет ноября — текущего месяца»): текущий месяц на графике есть, если в
   данных за него есть рабочие дни (точка «по N-е»). Строка под графиком говорит, по какую дату данные о посещениях; если
   за текущий месяц их ещё нет — прямо об этом, а не молча без точки */
function offNow(lp){
  if(!D.REAL||!D.PARTIAL)return '';
  const cur=D.aggregate(lp,'office_att')[D.LAST], a=D.offAsof&&D.offAsof(), mon=D.MONTH_NOM[D.MONTHS[D.LAST].m];
  const till=a?'Данные о посещениях — по '+a.label+'.':'';
  return '<div class="tbl-note">'+(cur==null||!isFinite(cur)
    ?'За '+esc(mon)+' данных о посещениях пока нет — точки этого месяца на графике нет. '+esc(till||'Она появится, когда источник посещений обновится.')
    :esc(mon.charAt(0).toUpperCase()+mon.slice(1))+' ещё идёт: его точка — по неполному месяцу, с полными месяцами её не сравниваем. '+esc(till))+'</div>';
}
/* Поставка 66: «Кто и где ходит» на настоящих — динамика (по сегменту, если выбран), сегмент со счётом людей,
   города офиса: посещения, люди и доля посещений. Город не выбирается: посещаемости города нет — есть посещения */
function attendReal(ctx,x,lbl,attTbl){
  const S=ctx.S, cc=x.city&&x.city.people;
  /* файл 8, п. 5: таблица «Сегмент» при выборе города не меняет вид — та же посещаемость по сегментам, пересчитанная для
     города (посещения в его офисах ÷ рабочие дни сегмента), в подписи — люди сегмента, бывшие в офисе города */
  /* поставка 107 (как мастер): владельцы фиксов — своя посещаемость отдельной строкой (часть численности, не сегмент) */
  const segTbl=attTbl('Сегмент',(cc?x.city.name+' · ':'')+D.PER_MON,x.segs.filter(s=>cc||s.hc>0).map(s=>({name:s.name,
      note:D.fmtInt(s.hc)+' чел'+(cc?' в офисе':''),
      value:s.att,color:G.C_OFFICE,on:S.offSeg===s.key,attr:'data-offseg="'+esc(s.key)+'"',
      attrTip:'Клик — динамика посещаемости и города только у «'+s.name+'».'})).concat(x.fix&&!cc&&!x.seg?[{name:'Владельцы фиксов',
      note:'фиксированное место · '+D.fmtInt(x.fix.wd)+' раб. дней',value:x.fix.att,color:G.C_OFFICE}]:[]),'Сравнение сегментов');
  /* поставка 128 (аудит: выбран город — таблицы по нему, а динамика та же, без подписи): помесячной посещаемости по городам в
     данных нет (у рабочего дня нет города) — динамика по всем городам, так и подписано */
  return SC.metricLine('office_att',ctx.lp,ctx.bl,S,{ann:lbl?null:ctx.ann.office_att,yser:x.yser,h:260,fill:false,
      title:'Посещаемость офиса'+(x.seg?': '+x.seg.name:'')+(x.city?(x.cityDyn?' — '+x.city.name:' — все города'):'')+', %'})+
    /* поставка 136, п. 19: выбран город — динамика по нему (посещения в офисах города ÷ рабочие дни людей с закреплённым
       офисом этого города). Где ряда города нет (строка таблицы, город вместе с сегментом, ноутбук до 136) — сказано прямо */
    (x.city?'<div class="tbl-note">'+(x.cityDyn?'Динамика — по городу офиса «'+esc(x.city.name)+'»: посещения в офисах города ÷ рабочие дни людей, '+
      'за которыми закреплён офис этого города. Сброс выбора города возвращает все города.'
      :'Город «'+esc(x.city.name)+'» на динамику здесь не влияет: помесячные данные по городу есть только у подразделения из фильтра и '+
        'без выбора сегмента. По городу пересчитаны таблицы ниже.')+'</div>':'')+
    offNow(ctx.lp)+
    (x.segs.length?segTbl:'')+
    /* 27.10-в, п. 15: по убыванию посещений, первые 10 и раскрываемые «Остальные»; 31.10-б, п. 9: колонка «Посещаемость»,
       строка города выбирается (кросс-фильтр с сегментом) */
    /* поставка 107 (как мастер): с рабочими днями города (ocd) — посещаемость города = посещения ÷ рабочие дни, иначе (сегмент
       выбран или ноутбук до 107) — посещения */
    (x.cities.length?U.btGroup(Object.assign(x.cityAtt?{cap:'Город офиса',capSub:D.PER_MON+' · посещаемость',head:'',
      valueHead:'Посещаемость',barHead:'Сравнение городов',metricKey:'office_att',share:false,compact:true,total:false,sort:true,
      items:x.cities.map(c=>Object.assign({name:c.name,note:D.fmtInt(c.visits)+' посещ. · '+D.fmtInt(c.people)+' чел',
        value:c.att,color:G.C_OFFICE},x.cross?{on:S.offCity===c.name,attr:'data-offcity="'+esc(c.name)+'"',
        attrTip:'Клик — сколько руководителей и сотрудников в «'+c.name+'».'}:{}))}
      :{cap:'Город офиса',capSub:(x.seg?x.seg.name+' · ':'')+D.PER_MON+' · посещения',head:'',
      valueHead:'Посещений',barHead:'Распределение',metricKey:'hc_total',compact:true,total:false,sort:true,items:x.cities.map(c=>Object.assign({name:c.name,
        note:D.fmtInt(c.people)+' чел',value:c.visits,color:G.C_OFFICE},x.cross?{on:S.offCity===c.name,
        attr:'data-offcity="'+esc(c.name)+'"',attrTip:'Клик — сколько руководителей и сотрудников в «'+c.name+'».'}:{}))},
      SC.rest(ctx,'ocity',10,['город','города','городов']))):'')+
    '<div class="tbl-note">'+(x.cityAtt?'Посещаемость города — посещения ÷ рабочие дни людей с закреплённым офисом этого города; '+
      'посещение — главный офис дня, как в мастер-отчёте':'Город — где было посещение: человек бывает в нескольких. По сегменту — '+
      'число посещений')+(x.cross?'; выбор сегмента и города складывается':'')+'.</div>';
}

SC.blocks.office={
  subTabs:[['calendar','Календарь'],['attend','Кто и где ходит'],['booking','Бронирование']],
  defaultSub:'calendar',
  /* поставка 136, п. 16 (владелец: «неясно, за какой период и что именно посчитано»): в шапке таблицы подразделений —
     полные названия с единицами и период под каждым; в подсказке — что в числителе и знаменателе */
  perAlways:true,
  colNames:{office_att:'Посещаемость, %',booking_viol:'Брони без посещения, %'},
  colTips:{office_att:'Доля рабочих дней, в которые сотрудники были в офисе.\n• Считаем: дни с посещением офиса ÷ рабочие дни × 100%\n• Посещение — день, когда человек был в офисе; бронь для этого не нужна',
    booking_viol:'Доля броней рабочего места, по которым человек не пришёл.\n• Считаем: брони без посещения ÷ все брони × 100%\n• Это не посещаемость: посещения без брони сюда не входят'},
  title(sub){return sub==='attend'?'Кто и где ходит в офис: динамика, сегмент, локация'
    :sub==='booking'?'Качество бронирования рабочих мест'
    :'Когда люди приходят в офис'},
  /* выбор вкладки «Кто и где ходит» — пилюлями в шапке карточки графиков (поставка 82) */
  shelfChips(S){
    if(S.subTab!=='attend')return [];
    const seg=S.offSeg?D.OFF_SEGS.find(x=>x.key===S.offSeg):null, chips=[], tip='Динамика и таблицы — по выбору.';
    /* поставка 128: на настоящих данных город динамику не меняет (по городам помесячно данных нет) — так и в подсказке */
    const real=!!S.offCity&&D.officeCross(D.reportLeaves(S),null,null).real;
    if(seg)chips.push({dim:'Сегмент',cat:seg.name,attr:'data-offseg="'+esc(seg.key)+'"',tip:tip});
    if(S.offCity)chips.push({dim:'Локация',cat:S.offCity,attr:'data-offcity="'+esc(S.offCity)+'"',
      tip:real?'Город офиса — где были посещения. Таблицы и динамика — по выбранному городу; где помесячных данных города нет, это сказано под графиком.':tip});
    return chips;
  },
  view(ctx){
    /* Таблицы посещаемости — проценты: доля процента в сумме процентов ничего
       не значит, поэтому ни колонки «Доля», ни строки ИТОГО у них нет. */
    const attTbl=(cap,capSub,items,barHead)=>U.btGroup({cap:cap,capSub:capSub,head:'',metricKey:'office_att',
      valueHead:'Посещаемость',barHead:barHead,share:false,total:false,compact:true,items:items});

    /* 22.10: динамика → сегмент → локация. Клик по строке сегмента или города — выбор; оба выбора
       складываются («руководители в Москве»): динамика и соседняя таблица считаются по нему */
    if(ctx.sub==='attend'){
      const S=ctx.S, x=D.officeCross(ctx.lp,S.offSeg,S.offCity), lbl=offLabel(x);
      if(!x.cities.length&&!x.segs.some(s=>s.hc))return U.empty('Нет данных о посещаемости','В отборе нет сотрудников.');
      if(x.real)return attendReal(ctx,x,lbl,attTbl);
      return SC.metricLine('office_att',ctx.lp,ctx.bl,S,{ann:lbl?null:ctx.ann.office_att,scale:x.factor,h:260,fill:false,
          title:'Посещаемость офиса'+(lbl?': '+lbl:'')+', %'})+
        attTbl('Сегмент',x.city?x.city.name+' · '+D.PER_MON:D.PER_MON,x.segs.filter(s=>s.hc>0).map(s=>({name:s.name,
          note:D.fmtInt(s.hc)+' чел',value:s.att,color:G.C_OFFICE,on:S.offSeg===s.key,attr:'data-offseg="'+esc(s.key)+'"',
          attrTip:'Клик — посещаемость только у «'+s.name+'»: пересчитаются динамика и города.'})),'Сравнение сегментов')+
        attTbl('Локация',x.seg?x.seg.name+' · '+D.PER_MON:D.PER_MON,x.cities.filter(c=>c.hc>0).map(c=>({name:c.name,
          note:D.fmtInt(c.hc)+' чел · '+c.offices+' '+U.plural(c.offices,['офис','офиса','офисов']),
          value:c.att,color:G.C_OFFICE,on:S.offCity===c.name,attr:'data-offcity="'+esc(c.name)+'"',
          attrTip:'Клик — посещаемость только в «'+c.name+'»: пересчитаются динамика и сегменты.'})),'Сравнение городов')+
        '<div class="tbl-note">В городе — среднее по его офисам с учётом числа людей.</div>';
    }

    if(ctx.sub==='booking'){
      const bk=D.bookingQuality(ctx.lp), vc=D.violByCity(ctx.lp);
      /* Человеко-дни, а не люди: один сотрудник за месяц может и прийти без
         брони, и не прийти по брони. Нарушения — две нижние строки. */
      /* поставка 107 (владелец, как мастер): две доли — брони без посещения (метрика) и посещения без брони; ниже — брони и
         посещения частями (ИТОГО — все брони / все посещения) */
      const nb=D.yoySeries(ctx.lp,'visit_nobook');
      return SC.metricLine('booking_viol',ctx.lp,ctx.bl,ctx.S,
          {h:230,fill:false,title:'Брони без посещения, %',ann:ctx.ann.booking_viol})+
        (D.REAL?SC.metricLine('booking_viol',ctx.lp,ctx.bl,ctx.S,{yser:nb,periodKey:'visit_nobook',noBench:true,kpi:null,h:230,fill:false,
          title:'Посещения без брони, %',name:'Посещения без брони',tipName:'Посещения без брони'}):'')+
        U.btStack([U.btGroup({cap:'Брони',capSub:D.PER_MON+', человеко-дни',head:'',
          valueHead:'Дней',metricKey:'hc_total',totUnit:' чел.-дн.',compact:true,keepZero:true,shareDec:true,items:[
          {name:'С посещением',value:bk.ok,color:G.C_OFFICE},
          {name:'Без посещения',note:'место простояло',value:bk.noshow,color:G.C_OFFICE}]}),
        U.btGroup({cap:'Посещения',capSub:D.PER_MON+', человеко-дни',head:'',
          valueHead:'Дней',metricKey:'hc_total',totUnit:' чел.-дн.',compact:true,keepZero:true,shareDec:true,items:[
          {name:'С бронью',value:bk.visitBk,color:G.C_OFFICE},
          {name:'Без брони',note:'место не учтено',value:bk.walkin,color:G.C_OFFICE}]})])+
        '<div class="tbl-note">Как в мастер-отчёте: доля броней без посещения — от всех броней, доля посещений без брони — от всех '+
          'посещений (главный офис дня) за '+esc(D.PER_MON)+'.</div>'+
        /* 27.10-в, п. 14–15: после «Бронирований и посещений» — нарушения по городам: по убыванию, первые 10 и
           раскрываемые «Остальные» */
        (!vc?'<div class="tbl-note">Нарушения бронирования по городам появятся, когда ноутбук отчёта обновят до поставки 70.</div>'
        :vc.length?U.btGroup(Object.assign({cap:'Нарушения бронирования по городам',capSub:D.PER_MON+', человеко-дни',head:'',
          valueHead:'Нарушений',metricKey:'hc_total',compact:true,total:false,sort:true,items:vc.map(c=>({name:c.name,
            note:c.pct!=null?U.pct(c.pct)+' от броней и посещений без брони':'',value:c.viol,color:G.C_OFFICE}))},
          SC.rest(ctx,'vcity',10,['город','города','городов']))):'');
    }

    /* календарь + дни недели: сетка отвечает «в какие дни», таблица — «в какие
       дни недели», и вместе они читаются как один ответ */
    /* поставка 128 (аудит: «Чаще всего ходят в среду» — по августу и сентябрю, а календарь под ним — сентябрь и 1–12 октября, где
       впереди понедельник): календарь — те же закрытые месяцы, что заголовок и таблица дней недели (D.PER_I); незакрытый месяц
       в итог не входит и здесь не показан */
    const blocks=D.attLast(ctx.lp,D.REAL?D.DOW_MONTHS:null,D.REAL?D.PER_I:null), dow=D.attByDow(ctx.lp);
    /* конец периода называем явно: иначе непонятно, почему текущий месяц
       оборван и на каком именно дне */
    const end=blocks[blocks.length-1];
    /* Календарь БЕЗ fill и без своей высоты — единственный такой график в правых
       панелях, и намеренно. fill отдал бы ему всю высоту панели, а клетка всё
       равно упирается в потолок: излишек оставался пустотой между календарём и
       таблицей дней недели и рос вместе с экраном (26px на ноутбуке, 500px на
       большом мониторе). Теперь календарь стоит своей высотой, до таблицы
       ровно --chart-gap, как между любыми двумя графиками, а запас высоты
       копится внизу панели. */
    /* ревью 100: посещения по дням датасет отдаёт только у юнита из фильтра — при выбранной строке говорим это прямо */
    /* поставка 136, п. 17: у подразделений первого уровня дни есть — календарь и дни недели пересчитаны по строке; глубже —
       по всему подразделению из фильтра, с пояснением */
    const own=D.REAL&&ctx.sel!==ctx.root&&!D.offDays(ctx.lp)?'<div class="tbl-note">Календарь и дни недели — по всему «'+esc((D.NODE_BY_PATH[ctx.root]||{}).name||'')+
      '»: по дням данные есть только у подразделения из фильтра. Чтобы увидеть «'+esc((D.NODE_BY_PATH[ctx.sel]||{}).name||'')+
      '», выберите его в «Настрой свой дашборд».</div>':'';
    return own+G.chart('calendar',{blocks:blocks},
      {title:D.REAL?'Посещаемость по дням — '+blocks.map(b=>D.MONTH_NOM[b.m]).join(' и ')+' '+end.y+', %'
        :'Посещаемость по дням — по '+end.to+' '+D.MONTH_GEN[end.m]+' '+end.y+', %'})+
      '<div class="bt-group"><div class="bt-cap">По дням недели, среднее за '+
      (D.DOW_MONTHS===2?D.MONTH_NOM[(D.PER_C+11)%12]+' и '+D.MONTH_NOM[D.PER_C]:D.DOW_MONTHS+' месяца')+'</div>'+
      U.barTable({head:'День недели',metricKey:'office_att',valueHead:'Посещаемость',
        barHead:'Сравнение дней',share:false,total:false,compact:true,
        items:dow.map(d=>({name:d.name,value:d.value,
          color:d.weekend?G.C_FLAT:G.C_OFFICE,note:d.weekend?'выходной':''}))})+
      '<div class="tbl-note">'+esc(CAL_NOTE)+'</div></div>';
  }
};
})();
