/* ============================================================================
   screens/structure.js — Структура численности.

   Было четыре под-вкладки: грейды, стаж, штат/не штат, динамика. Три из них
   показывали по одному кольцу, и чтобы увидеть состав команды приходилось
   перекликивать. Осталась одна — «Разбивки по атрибутам»: все три разреза
   таблицами на одном экране.

   Кольца убраны: доля читается по числу и полосе в таблице точнее, чем по
   углу сектора, и таблица заодно даёт абсолютные значения.

   Динамика численности переехала в «Движение персонала», к водопаду баланса:
   численность и потоки, которые её меняют, — один вопрос, и смотреть их надо
   рядом, а не на разных вкладках разных блоков.
   ========================================================================== */
(function(){
'use strict';
const D=window.TPDATA, U=window.TPUI, SC=window.TPSCREENS;

const DIMS=[['grade','По грейдам'],['tenure','По стажу в компании'],['staff','Штат и не штат']];

SC.blocks.structure={
  subTabs:[['breakdown','Разбивки по атрибутам']],
  defaultSub:'breakdown',
  title(){return 'Состав численности по атрибутам'},
  view(ctx){
    /* все три разреза сразу: сравнивать между собой можно не перекликивая */
    return '<div class="bt-stack">'+DIMS.map(([dim,name])=>{
      const cats=D.mixCats(dim), parts=D.mixParts(ctx.lp,dim);
      return '<div class="bt-group"><div class="bt-cap">'+U.esc(name)+'</div>'+
        U.barTable({head:name.replace(/^По /,'').replace(/^./,c=>c.toUpperCase()),
          items:cats.map((c,i)=>({name:c.name,value:parts[i],color:c.color})),
          metricKey:'hc_total',compact:true})+'</div>';
    }).join('')+'</div>';
  }
};
})();
